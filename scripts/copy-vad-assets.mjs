#!/usr/bin/env node
/**
 * Copy Silero VAD model + onnxruntime-web WASM next to the SPA so the browser
 * loads them same-origin (no jsDelivr). Fixes production "Failed to fetch"
 * / 404 when CDN is blocked or ORT CDN version drifts from vad-web.
 */
import { cpSync, existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outRoot = join(root, "public", "vad");
const outOrt = join(outRoot, "ort");

/** Resolve package root even when package.json is not in "exports". */
function pkgRoot(name, fromDir = root) {
  const candidates = [
    join(fromDir, "node_modules", name),
    join(root, "node_modules", name),
    join(root, "node_modules", "@ricky0123", "vad-web", "node_modules", name)
  ];
  for (const c of candidates) {
    if (existsSync(join(c, "package.json"))) return c;
  }
  // Last resort: resolve a real export entry then walk up.
  try {
    const resolved = require.resolve(name, { paths: [fromDir, root] });
    let dir = dirname(resolved);
    for (let i = 0; i < 8; i++) {
      if (existsSync(join(dir, "package.json"))) return dir;
      const parent = dirname(dir);
      if (parent === dir) break;
      dir = parent;
    }
  } catch {
    /* fall through */
  }
  throw new Error(`cannot locate package ${name}`);
}

function main() {
  const vadRoot = pkgRoot("@ricky0123/vad-web");
  const vadDist = join(vadRoot, "dist");
  // Prefer the ORT nested under vad-web (version it was tested with).
  let ortDist;
  try {
    ortDist = join(pkgRoot("onnxruntime-web", vadRoot), "dist");
  } catch {
    ortDist = join(pkgRoot("onnxruntime-web"), "dist");
  }

  if (!existsSync(join(vadDist, "silero_vad_v5.onnx"))) {
    throw new Error(`missing silero_vad_v5.onnx under ${vadDist}`);
  }
  if (!existsSync(ortDist)) {
    throw new Error(`missing onnxruntime-web dist at ${ortDist}`);
  }

  rmSync(outRoot, { recursive: true, force: true });
  mkdirSync(outOrt, { recursive: true });

  // Models + AudioWorklet bundle (MicVAD loads baseAssetPath + "vad.worklet.bundle.min.js").
  // Without the worklet file, audioWorklet.addModule receives SPA index.html → AbortError.
  const vadRootFiles = [
    "silero_vad_v5.onnx",
    "silero_vad_legacy.onnx",
    "vad.worklet.bundle.min.js",
    "vad.worklet.bundle.dev.js"
  ];
  const copiedVad = [];
  for (const f of vadRootFiles) {
    const src = join(vadDist, f);
    if (!existsSync(src)) {
      // dev bundle is optional; min worklet + models are required for production voice.
      if (f === "vad.worklet.bundle.dev.js") continue;
      throw new Error(`missing ${f} under ${vadDist}`);
    }
    cpSync(src, join(outRoot, f));
    copiedVad.push(f);
  }

  // ORT 1.17+ wasm/jsep bundles used by vad-web MicVAD.
  // Core pair is required; jsep/asyncify/jspi variants are copied when present
  // so runtime can pick the matching backend without CDN fallback.
  const requiredOrtFiles = [
    "ort-wasm-simd-threaded.wasm",
    "ort-wasm-simd-threaded.mjs"
  ];
  const optionalOrtFiles = [
    "ort-wasm-simd-threaded.jsep.wasm",
    "ort-wasm-simd-threaded.jsep.mjs",
    "ort-wasm-simd-threaded.asyncify.wasm",
    "ort-wasm-simd-threaded.asyncify.mjs",
    "ort-wasm-simd-threaded.jspi.wasm",
    "ort-wasm-simd-threaded.jspi.mjs"
  ];
  const copiedOrt = [];
  for (const f of requiredOrtFiles) {
    const src = join(ortDist, f);
    if (!existsSync(src)) {
      throw new Error(`missing required ORT asset ${f} under ${ortDist}`);
    }
    cpSync(src, join(outOrt, f));
    copiedOrt.push(f);
  }
  for (const f of optionalOrtFiles) {
    const src = join(ortDist, f);
    if (existsSync(src)) {
      cpSync(src, join(outOrt, f));
      copiedOrt.push(f);
    }
  }

  writeFileSync(
    join(outRoot, "README.txt"),
    "Generated by scripts/copy-vad-assets.mjs — do not edit. Served at /vad/.\n",
    "utf8"
  );
  console.log(
    JSON.stringify(
      {
        event: "vad_assets_copied",
        outRoot,
        ortDist,
        vadFiles: copiedVad,
        ortFiles: copiedOrt
      },
      null,
      0
    )
  );
}

main();
